// Regenerate lib/scoring/wordlist-data.mjs.
//
//   node scripts/build-wordlist.mjs
//
// The spell checker bundles its dictionary as a gzipped base64 string in a JS
// module rather than installing a package or reading a data file. Two reasons:
// the calibration script and the deployed scorer then use byte-identical
// dictionaries, and scoring an essay never depends on a package manager or on
// serverless file tracing.
//
// Source list is words_alpha (public domain, dwyl/english-words). It includes
// inflected and irregular forms, which matters: a stem-only hunspell list omits
// "is" entirely, and flagging "is" as a misspelling would punish good writers.
// For essay scoring, a false positive costs far more than a missed typo.

import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import zlib from 'node:zlib';

const SOURCE = 'https://raw.githubusercontent.com/dwyl/english-words/master/words_alpha.txt';
const MIN_LENGTH = 1;
const MAX_LENGTH = 28;

async function main() {
  process.stdout.write('Fetching word list... ');
  const response = await fetch(SOURCE);
  if (!response.ok) throw new Error(`${SOURCE} returned HTTP ${response.status}`);
  const raw = await response.text();
  console.log(`${(raw.length / 1024 / 1024).toFixed(1)} MB`);

  const words = [
    ...new Set(
      raw
        .split(/\r?\n/)
        .map((word) => word.trim().toLowerCase())
        .filter((word) => word.length >= MIN_LENGTH && word.length <= MAX_LENGTH && /^[a-z]+$/.test(word))
    ),
  ].sort();

  const gzipped = zlib.gzipSync(Buffer.from(words.join('\n'), 'utf8'), { level: 9 });
  const base64 = gzipped.toString('base64');

  const module = [
    '// Generated by scripts/build-wordlist.mjs. Do not edit by hand.',
    '// Source: words_alpha from dwyl/english-words (public domain).',
    '// Bundled so calibration and production share one dictionary and scoring',
    '// never depends on an install step.',
    `// ${words.length} words, ${(gzipped.length / 1024).toFixed(0)} KB gzipped.`,
    'export const WORDLIST_GZIP_BASE64 =',
    `  '${base64}';`,
    '',
  ].join('\n');

  const target = path.join(process.cwd(), 'lib', 'scoring', 'wordlist-data.mjs');
  await writeFile(target, module, 'utf8');

  console.log(`${words.length} words, ${(gzipped.length / 1024).toFixed(0)} KB gzipped, ${(module.length / 1024).toFixed(0)} KB module.`);
  console.log(`Wrote ${target}`);
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
